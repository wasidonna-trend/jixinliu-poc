const I18N_LANGS = ["zh-TW", "zh-CN", "en", "it"];

function detectLang() {
  const stored = localStorage.getItem("jixin_lang");
  if (stored && I18N[stored]) return stored;
  const nav = (navigator.languages || [navigator.language || "en"]).map(l => l.toLowerCase());
  for (const l of nav) {
    if (l === "zh-cn" || l === "zh-hans" || l.startsWith("zh-cn") || l.startsWith("zh-hans")) return "zh-CN";
    if (l.startsWith("zh")) return "zh-TW";
    if (l.startsWith("it")) return "it";
    if (l.startsWith("en")) return "en";
  }
  return "zh-TW";
}

let CURRENT_LANG = detectLang();

function applyLang(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem("jixin_lang", lang);
  const dict = I18N[lang] || I18N["zh-TW"];
  document.documentElement.lang = lang;

  // body classes for font swapping
  document.body.classList.remove("lang-zh", "lang-cn", "lang-en", "lang-it");
  if (lang === "zh-TW") document.body.classList.add("lang-zh");
  else if (lang === "zh-CN") document.body.classList.add("lang-cn");
  else if (lang === "en") document.body.classList.add("lang-en");
  else if (lang === "it") document.body.classList.add("lang-it");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.getAttribute("data-i18n");
    if (dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const k = el.getAttribute("data-i18n-html");
    if (dict[k] !== undefined) el.innerHTML = dict[k];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const k = el.getAttribute("data-i18n-placeholder");
    if (dict[k] !== undefined) el.setAttribute("placeholder", dict[k]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const k = el.getAttribute("data-i18n-aria");
    if (dict[k] !== undefined) el.setAttribute("aria-label", dict[k]);
  });
  // Lang switcher active state
  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.getAttribute("data-lang") === lang);
  });

  // Notify listeners (e.g. dynamic page-specific content)
  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang, dict } }));
}

function t(key) {
  const dict = I18N[CURRENT_LANG] || I18N["zh-TW"];
  return dict[key] !== undefined ? dict[key] : key;
}

function initLangSwitcher(root) {
  (root || document).querySelectorAll(".lang-switch button").forEach(btn => {
    btn.addEventListener("click", () => applyLang(btn.getAttribute("data-lang")));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(CURRENT_LANG);
  initLangSwitcher();

  // Reveal observer
  const io = new IntersectionObserver((entries) => {
    entries.forEach(e => { if (e.isIntersecting) e.target.classList.add("in"); });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach(el => io.observe(el));

  // Nav scroll state
  const nav = document.querySelector(".nav");
  if (nav) {
    const onScroll = () => nav.classList.toggle("scrolled", window.scrollY > 12);
    window.addEventListener("scroll", onScroll, { passive: true });
    onScroll();
  }

  // Mobile burger
  const burger = document.querySelector(".nav-burger");
  const links  = document.querySelector(".nav-links");
  if (burger && links) {
    burger.addEventListener("click", () => links.classList.toggle("open"));
    links.querySelectorAll("a").forEach(a => a.addEventListener("click", () => links.classList.remove("open")));
  }
});
